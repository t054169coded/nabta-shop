/** Current language, remembered between visits. */
function getLang () {
  return localStorage.getItem('nabta.lang') === 'ar' ? 'ar' : 'en';
}

/** Look up a string and substitute {placeholders}. */
function t (key, vars = {}) {
  const lang = getLang();
  let out = STRINGS[lang][key] ?? STRINGS.en[key] ?? key;
  for (const [k, v] of Object.entries(vars)) out = out.replaceAll(`{${k}}`, v);
  return out;
}

/** Fill every [data-i18n] element on the page, and flip the document direction. */
function applyLanguage (lang = getLang()) {
  localStorage.setItem('nabta.lang', lang);
  /* i18n writes this key directly rather than through app.js's write(), so
     the sync hook has to be called here too. */
  if (typeof schedulePush === 'function') schedulePush('nabta.lang');
  const html = document.documentElement;
  html.lang = lang;
  html.dir = lang === 'ar' ? 'rtl' : 'ltr';

  document.querySelectorAll('[data-i18n]').forEach(el => {
    el.textContent = t(el.dataset.i18n);
  });
  /* A few strings carry inline emphasis. They come from the table above and
     never from user input, so innerHTML is safe here. */
  document.querySelectorAll('[data-i18n-html]').forEach(el => {
    el.innerHTML = t(el.dataset.i18nHtml);
  });
  document.querySelectorAll('[data-i18n-ph]').forEach(el => {
    el.placeholder = t(el.dataset.i18nPh);
  });
  document.querySelectorAll('[data-i18n-label]').forEach(el => {
    el.setAttribute('aria-label', t(el.dataset.i18nLabel));
  });
  document.dispatchEvent(new CustomEvent('languagechange', { detail: { lang } }));
}
